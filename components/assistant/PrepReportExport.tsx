'use client'

import { Button } from '@/components/ui/button'
import { Download, FileText } from 'lucide-react'
import { DeterministicPatternStats, PatternChangeShifts, LikelyTopicPrediction } from '@/lib/analytics/pattern'

interface PrepReportExportProps {
  courseCode: string
  stats: DeterministicPatternStats
  shifts: PatternChangeShifts
  predictions: LikelyTopicPrediction[]
}

export function PrepReportExport({
  courseCode,
  stats,
  shifts,
  predictions,
}: PrepReportExportProps) {
  function handleDownload() {
    const markdown = `# ${courseCode} — Mid-Semester Test (MST) Comprehensive Prep Report
Generated by Thapar Smart Exam-Prep Platform (TIET-Prep)
Date: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}

---

## 1. Exam Structure & Historical Pattern
- **Total Papers Analyzed**: ${stats.totalPapersAnalyzed} (${stats.yearsAnalyzed.join(', ')})
- **Average Questions / Paper**: ${stats.avgQuestionsPerPaper} (Sections A & B)
- **Total Marks Allocation**: ${stats.avgPaperMarks} Marks (2 Hours Duration)
- **Question Types Distribution**:
${Object.entries(stats.typeDistribution)
  .map(([k, v]) => `  - **${k}**: ${v.percentage}% of marks (${v.marks}M total)`)
  .join('\n')}
- **Cognitive Rigor**:
${Object.entries(stats.difficultyDistribution)
  .map(([k, v]) => `  - **${k}**: ${v.percentage}%`)
  .join('\n')}

---

## 2. Typical Professor Phrasing & Command Words
${stats.commandWords.map((cw) => `- **"${cw.word}"**: Appears in ${cw.percentage}% of past questions`).join('\n')}

---

## 3. Detected Multi-Year Pattern Shifts
${shifts.shifts
  .map(
    (s) =>
      `### ${s.category} [${s.trend}]
- **Observation**: ${s.observation}
- **Metric Shift**: ${s.metricChange}`
  )
  .join('\n\n')}

---

## 4. Ranked Likely-Topic Predictions (Probability Estimates)
${predictions
  .map(
    (p, i) => `### ${i + 1}. ${p.topic}
- **Confidence Level**: ${p.confidenceScore}% (${p.confidenceLabel})
- **Historical Marks Share**: ${p.historicalMarksShare}%
- **Evidence from Past Papers**: ${p.evidence.pastPaperOccurrences.join(', ')}
- **Lecture Slide Sources**: ${p.evidence.slideDecks.join(', ')}
- **Rationale**: ${p.evidence.rationale}
- **Recommended Action**: ${p.recommendedAction}`
  )
  .join('\n\n')}

---

## 5. Academic Disclaimer
All predictions and weightage analytics are computed deterministically from approved past TIET examination papers. They represent strategic preparation estimates and not guarantees. Students are advised to review the full course syllabus.
`

    const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' })
    const link = document.createElement('a')
    link.href = window.URL.createObjectURL(blob)
    link.setAttribute('download', `${courseCode}-MST-Prep-Report.md`)
    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
  }

  return (
    <Button
      variant="outline"
      size="sm"
      onClick={handleDownload}
      className="text-xs border-border/70 text-foreground hover:bg-secondary"
    >
      <Download className="h-3.5 w-3.5 mr-1.5" />
      Download Prep Report (.md)
    </Button>
  )
}
